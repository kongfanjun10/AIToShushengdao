const LEVELS = RAW.map((lv, li) => ({
  key: lv.key,
  name: lv.name,
  sub: lv.sub,
  note: lv.note,
  index: li,
  total: lv.chars.length,
  chars: lv.chars.map((row, i) => ({
    id: lv.key + "_" + i,
    index: i,
    c: row[0],
    py: row[1],
    words: row[2],
    levelKey: lv.key,
  })),
}));

function getLevel(key) {
  return LEVELS.filter((l) => l.key === key)[0] || LEVELS[0];
}

function findChar(levelKey, char) {
  const lv = getLevel(levelKey);
  return lv.chars.filter((x) => x.c === char)[0] || lv.chars[0];
}

/** 全部字（按学段顺序），用于统计总进度 */
function allChars() {
  let out = [];
  LEVELS.forEach((l) => {
    out = out.concat(l.chars);
  });
  return out;
}

module.exports = { LEVELS, getLevel, findChar, allChars };
